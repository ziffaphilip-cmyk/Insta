#!/usr/bin/env python3
"""Small helper for the content workspace. Standard library only.

Usage (from the repo root):
  python3 tools/content.py check            validate the CSV files
  python3 tools/content.py backlog          rebuild content/backlog.md from ideas.csv
  python3 tools/content.py week [YYYY-MM-DD] list calendar posts for the week containing that date
  python3 tools/content.py report           summarise content/tracker.csv
"""
import csv
import datetime as dt
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "content"
IDEAS = ROOT / "ideas.csv"
CALENDAR = ROOT / "calendar.csv"
TRACKER = ROOT / "tracker.csv"
BACKLOG = ROOT / "backlog.md"

FORMATS = {"talking", "overlay"}
PILLARS = {"strength", "mindset", "lifestyle", "opinions", "relatable"}
STATUSES = ["idea", "scripted", "filmed", "edited", "published"]
EFFORTS = {"S", "M", "L"}


def read(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(value):
    """Parse a tracker number like '12,400' or '12.4k'. Blank means unknown."""
    v = (value or "").strip().lower().replace(",", "")
    if not v:
        return None
    mult = 1
    if v.endswith("k"):
        mult, v = 1000, v[:-1]
    elif v.endswith("m"):
        mult, v = 1_000_000, v[:-1]
    try:
        return float(v) * mult
    except ValueError:
        return None


def check():
    problems = []
    ideas = read(IDEAS)
    ids = set()
    for n, r in enumerate(ideas, start=2):
        where = f"ideas.csv line {n} ({r.get('id')})"
        if r["id"] in ids:
            problems.append(f"{where}: duplicate id")
        ids.add(r["id"])
        if r["format"] not in FORMATS:
            problems.append(f"{where}: format must be one of {sorted(FORMATS)}")
        if r["pillar"] not in PILLARS:
            problems.append(f"{where}: pillar must be one of {sorted(PILLARS)}")
        if r["status"] not in STATUSES:
            problems.append(f"{where}: status must be one of {STATUSES}")
        if r["effort"] not in EFFORTS:
            problems.append(f"{where}: effort must be S, M or L")
        if not r["hook_or_overlay"].strip():
            problems.append(f"{where}: missing hook_or_overlay")

    for n, r in enumerate(read(CALENDAR), start=2):
        where = f"calendar.csv line {n}"
        try:
            dt.date.fromisoformat(r["date"])
        except ValueError:
            problems.append(f"{where}: date must be YYYY-MM-DD")
        if r["idea_id"] and r["idea_id"] not in ids:
            problems.append(f"{where}: idea_id {r['idea_id']} is not in ideas.csv")
        if r["status"] not in STATUSES:
            problems.append(f"{where}: status must be one of {STATUSES}")
        if r["format"] not in FORMATS:
            problems.append(f"{where}: format must be one of {sorted(FORMATS)}")

    for n, r in enumerate(read(TRACKER), start=2):
        where = f"tracker.csv line {n}"
        try:
            dt.date.fromisoformat(r["date"])
        except ValueError:
            problems.append(f"{where}: date must be YYYY-MM-DD")
        if r["idea_id"] and r["idea_id"] not in ids:
            problems.append(f"{where}: idea_id {r['idea_id']} is not in ideas.csv")

    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"OK: {len(ideas)} ideas, calendar and tracker look valid.")


def backlog():
    ideas = [r for r in read(IDEAS) if r["status"] != "published"]
    scheduled = {r["idea_id"] for r in read(CALENDAR) if r["status"] != "published"}
    out = ["# Backlog", "",
           "_Generated by `python3 tools/content.py backlog`. Edit `ideas.csv`, not this file._", "",
           "Ideas not yet published. 📅 = already on the calendar. ✍️ = needs your real story or details first.", ""]
    for fmt, label in (("talking", "Talking reels"), ("overlay", "Text-overlay reels")):
        out += [f"## {label}", ""]
        rows = sorted((r for r in ideas if r["format"] == fmt),
                      key=lambda r: (r["pillar"], r["effort"], r["id"]))
        for pillar in sorted({r["pillar"] for r in rows}):
            out += [f"### {pillar.capitalize()}", "", "| ID | Hook / overlay | Goal | Effort | Status |", "|---|---|---|---|---|"]
            for r in rows:
                if r["pillar"] != pillar:
                    continue
                flags = (" 📅" if r["id"] in scheduled else "") + \
                        (" ✍️" if r["needs_her_story"].lower().startswith(("yes", "confirm")) else "")
                hook = r["hook_or_overlay"].replace("\n", " / ").replace("|", "\\|")
                out.append(f"| {r['id']}{flags} | {hook} | {r['objective']} | {r['effort']} | {r['status']} |")
            out.append("")
    BACKLOG.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {BACKLOG.relative_to(ROOT.parent)} ({len(ideas)} ideas)")
    idea_cards()


def idea_cards():
    """Write content/ideas.md: every idea as a readable card, for phones and previews."""
    ideas = read(IDEAS)
    fields = [("angle", "Angle"), ("onscreen_text", "On-screen title"), ("alt_overlay", "Alternative"),
              ("audience", "For"), ("response", "Response"), ("objective", "Goal"), ("footage", "Footage"),
              ("audio", "Audio"), ("caption", "Caption"), ("cta", "Call to action"), ("why", "Why post it"),
              ("needs_her_story", "Needs from you")]
    out = ["# Idea bank", "",
           "_Generated from `ideas.csv` by `python3 tools/content.py backlog`. Edit the CSV, not this file._", ""]
    for fmt, label in (("talking", "Talking reels"), ("overlay", "Text-overlay reels")):
        out += [f"## {label}", ""]
        for r in (r for r in ideas if r["format"] == fmt):
            hook = r["hook_or_overlay"].replace("\n", "  \n> ")
            out += [f"### {r['id']} · {r['title']}", "",
                    f"`{r['pillar']}` · effort {r['effort']} · {r['status']}", "", f"> {hook}", ""]
            for key, name in fields:
                value = (r.get(key) or "").strip()
                if value and value.lower() != "no":
                    out.append(f"- **{name}:** {value.replace(chr(10), ' / ')}")
            out.append("")
    path = ROOT / "ideas.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {path.relative_to(ROOT.parent)} ({len(ideas)} ideas)")


def week(day=None):
    d = dt.date.fromisoformat(day) if day else dt.date.today()
    start = d - dt.timedelta(days=d.weekday())
    end = start + dt.timedelta(days=6)
    rows = [r for r in read(CALENDAR) if start <= dt.date.fromisoformat(r["date"]) <= end]
    print(f"Week of {start:%a %d %b} to {end:%a %d %b %Y}")
    if not rows:
        print("  Nothing scheduled.")
    for r in sorted(rows, key=lambda r: r["date"]):
        day_name = dt.date.fromisoformat(r["date"]).strftime("%a %d")
        print(f"  {day_name}  {r['idea_id']:4} {r['format']:8} {r['status']:9} {r['hook'][:70]}")


def report():
    rows = read(TRACKER)
    if not rows:
        print("tracker.csv has no posts yet. Log a post 7 days after publishing, then run this again.")
        return

    posts = []
    for r in rows:
        views = num(r["views"])
        p = {"label": f"{r['date']} {r['idea_id'] or ''} {r['hook'][:40]}".strip(),
             "format": r["format"], "pillar": r["pillar"], "views": views,
             "watch": num(r["avg_watch_pct"]), "feel": num(r["feel_1to5"])}
        for k in ("likes", "comments", "shares", "saves", "follows"):
            v = num(r[k])
            p[k] = (v / views * 1000) if (v is not None and views) else None
        posts.append(p)

    def med(values):
        vals = [v for v in values if v is not None]
        return statistics.median(vals) if vals else None

    def fmt(v, digits=1):
        return "  -  " if v is None else f"{v:,.{digits}f}"

    metrics = [("views", 0), ("watch", 0), ("shares", 1), ("saves", 1), ("comments", 1), ("follows", 2), ("feel", 1)]
    header = f"{'group':22} {'posts':>5} {'views':>9} {'watch%':>7} {'shr/1k':>7} {'sav/1k':>7} {'com/1k':>7} {'fol/1k':>7} {'feel':>5}"
    for key in ("format", "pillar"):
        groups = defaultdict(list)
        for p in posts:
            groups[p[key] or "?"].append(p)
        print(f"\nMedian by {key}  (rates are per 1,000 views, so small and big posts compare fairly)")
        print(header)
        for g, ps in sorted(groups.items()):
            vals = [fmt(med(p[m] for p in ps), d) for m, d in metrics]
            print(f"{g:22} {len(ps):>5} {vals[0]:>9} {vals[1]:>7} {vals[2]:>7} {vals[3]:>7} {vals[4]:>7} {vals[5]:>7} {vals[6]:>5}")

    print("\nStandouts within the same format (best rate vs that format's median):")
    for fmt_name in sorted({p["format"] for p in posts}):
        same = [p for p in posts if p["format"] == fmt_name]
        if len(same) < 3:
            print(f"  {fmt_name}: need 3+ posts to compare fairly (have {len(same)}).")
            continue
        for m, label in (("views", "reach"), ("shares", "shares"), ("saves", "saves"), ("follows", "follows")):
            scored = [p for p in same if p[m] is not None]
            if len(scored) < 3:
                continue
            best = max(scored, key=lambda p: p[m])
            base = med(p[m] for p in scored)
            if base:
                print(f"  {fmt_name:8} {label:8} {best['label']}  ({best[m] / base:.1f}x median)")

    if len(posts) < 8:
        print("\nNote: fewer than 8 posts logged. Treat any pattern as a hypothesis to test, not a conclusion.")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "check":
        check()
    elif cmd == "backlog":
        backlog()
    elif cmd == "week":
        week(sys.argv[2] if len(sys.argv) > 2 else None)
    elif cmd == "report":
        report()
    else:
        print(__doc__)
